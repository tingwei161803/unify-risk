// Offline generator for js/data/coefficients.js. Not loaded by the app.
//
// Reads the coefficient tables the team compiled from published papers (
// coefficients/*.json) and writes one ES module with every published number:
// coefficients, means, constants, baseline survival, points tables, score-to-risk
// tables and worked examples. The team's literature notes mix English and Chinese notes;
// this repo is English only, so:
//   - a translation in tools/coefficients-en.json (exact source string -> English)
//     is used when present;
//   - otherwise "English (Chinese)" keeps the English part;
//   - otherwise the text is dropped and listed in UNTRANSLATED.
// Numbers are never changed.
//
//   node tools/build-coefficients.mjs <path/to/coefficients-dir> > js/data/coefficients.js

import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/build-coefficients.mjs <coefficients-dir>');
  process.exit(1);
}

const enPath = new URL('./coefficients-en.json', import.meta.url);
const EN = existsSync(enPath) ? JSON.parse(readFileSync(enPath, 'utf8')) : {};
const CJK = /[　-鿿＀-￯]/;
const untranslated = new Map();

function clean(s, where) {
  if (typeof s !== 'string') return s;
  if (!CJK.test(s)) return s;
  if (EN[s]) return EN[s];
  // "English（中文）" or "English (中文)": keep the English part
  const stripped = s.replace(/[（(][^（）()]*[　-鿿][^（）()]*[）)]/g, '').replace(/\s{2,}/g, ' ').trim();
  if (stripped && !CJK.test(stripped)) return stripped;
  untranslated.set(s, where);
  return null;
}

// Walk any JSON value: keep numbers and booleans, clean strings, drop keys whose
// value became null. Keys are kept as they are (they are English in the source).
function walk(v, where) {
  if (Array.isArray(v)) return v.map((x) => walk(x, where)).filter((x) => x !== null && x !== undefined);
  if (v && typeof v === 'object') {
    const out = {};
    for (const [k, x] of Object.entries(v)) {
      if (CJK.test(k)) { untranslated.set(k, where + ' (key)'); continue; }
      const y = walk(x, where + '.' + k);
      if (y !== null && y !== undefined && !(typeof y === 'object' && !Array.isArray(y) && Object.keys(y).length === 0)) out[k] = y;
    }
    return out;
  }
  return clean(v, where);
}

const SKIP = new Set(['source_pdf', 'pitfalls', 'unresolved']); // working notes, not model data
const models = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const raw = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  const id = raw.model_id || f.replace(/\.json$/, '');
  const kept = {};
  for (const [k, v] of Object.entries(raw)) if (!SKIP.has(k)) kept[k] = v;
  models[id] = walk(kept, id);
}

// DUMP_UNTRANSLATED=path writes the dropped source strings (JSON array) for translation.
if (process.env.DUMP_UNTRANSLATED) writeFileSync(process.env.DUMP_UNTRANSLATED, JSON.stringify([...untranslated.keys()], null, 1));
const ids = Object.keys(models);
process.stdout.write(`// GENERATED by tools/build-coefficients.mjs from coefficient tables
// the team compiled from published papers. Do not edit by hand.
//
// ${ids.length} models. Every number is copied unchanged from the published paper,
// supplement or the authors' code, as recorded in the team's literature notes (each
// coefficient's "source" gives the table and page). Text that exists only in
// Chinese in the team's literature notes is left out until it is translated; see
// UNTRANSLATED (${untranslated.size} strings).
//
// Shapes vary a little by model type:
//   cox / logistic: equations[].coefficients[] { key, term, beta, mean, hr | odds_ratio },
//                   equations[].constants, equations[].baseline_survival { year: S0 }
//   points:         points_tables[].items[] { factor, category, points }, score_to_risk
//   all:            model_type, outcome, horizon_years, population, formula, citation, examples
// Models in the engine use the same ids as js/data/evidence.js where they overlap.

export const COEFFICIENTS = ${JSON.stringify(models, null, 1)};

export const UNTRANSLATED = ${JSON.stringify([...untranslated.values()].slice(0, 2000), null, 1)};

export function getCoefficients(modelId) {
  return COEFFICIENTS[modelId] || null;
}
`);
console.error(`${ids.length} models, ${untranslated.size} untranslated strings`);
