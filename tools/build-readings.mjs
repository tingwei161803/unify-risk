// Prepare the Explained page's AI reading for each fictional sample person, so the page can show
// it at once instead of waiting for the model. Offline tool, not part of the app.
//
//   node tools/build-readings.mjs                 # all sample people
//   node tools/build-readings.mjs --only chen,hsu # redo some, keep the rest of js/data/readings.js
//
// Each packet is built by js/views/explain-packet.js, the same code the page uses, and stored with its
// fingerprint: the page uses a prepared reading only when its own packet has the same fingerprint.
// The model call itself is api/interpret.py handle(), run through uv with the keys from .env
// (tools/build_readings.py). Keys are never printed or written anywhere.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { PERSONAS } from '../js/data/personas.js';
import { buildPacket, readingFingerprint } from '../js/views/explain-packet.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'js', 'data', 'readings.js');
const BANNED = /\b(diagnos\w*|screen\w*|detect\w*)/gi;

const onlyArg = process.argv.indexOf('--only');
const only = onlyArg > -1 ? new Set(String(process.argv[onlyArg + 1] || '').split(',').filter(Boolean)) : null;

// A sample person exactly as the store holds them right after loadPersona(): no confirmed reports yet.
const items = [];
for (const persona of PERSONAS) {
  if (only && !only.has(persona.id)) continue;
  const record = { personaId: persona.id, profile: { ...persona.profile }, labs: { ...persona.labs }, reports: [] };
  const { packet } = await buildPacket(record, persona);
  items.push({ id: persona.id, fingerprint: readingFingerprint(packet), packet });
}

const dir = mkdtempSync(path.join(tmpdir(), 'unify-readings-'));
const input = path.join(dir, 'packets.json');
const output = path.join(dir, 'readings.json');
writeFileSync(input, JSON.stringify(items));
execFileSync('uv', ['run', '--no-project', 'python', path.join(ROOT, 'tools', 'build_readings.py'), input, output],
  { cwd: ROOT, stdio: 'inherit' });
const replies = JSON.parse(readFileSync(output, 'utf8'));

let readings = {};
if (only) {
  try { readings = (await import(`${OUT}?t=${Date.now()}`)).READINGS || {}; } catch { readings = {}; }
}

const rows = [];
for (const item of items) {
  const r = replies[item.id] || {};
  const words = r.markdown ? r.markdown.split(/\s+/).filter(Boolean).length : 0;
  const banned = r.markdown ? (r.markdown.replace(/Not a diagnosis\./g, '').match(BANNED) || []) : [];
  rows.push({ id: item.id, seconds: r.seconds, model: r.model || '-', words, untraced: (r.untraced || []).length,
    banned: banned.length, error: r.error || '' });
  if (r.markdown && !r.error) {
    readings[item.id] = {
      fingerprint: item.fingerprint,
      markdown: r.markdown,
      model: r.model || null,
      provider: r.provider || null,
      generatedAt: new Date().toISOString(),
      numbersChecked: r.numbersChecked ?? null,
      untraced: r.untraced || []
    };
  }
}

const ordered = {};
for (const p of PERSONAS) if (readings[p.id]) ordered[p.id] = readings[p.id];
writeFileSync(OUT, `// GENERATED by tools/build-readings.mjs. Do not edit by hand; re-run the tool instead.
//
// The Explained page's AI reading for each fictional sample person, prepared in advance so the page
// shows it at once. A reading is used only when the page's own packet has the same fingerprint;
// edited answers or a newly confirmed report fall back to a live reading. Every person here is fictional.
// Not a diagnosis. Not medical advice.

export const READINGS = ${JSON.stringify(ordered, null, 2)};
`);

console.table(rows);
console.log(`wrote ${path.relative(ROOT, OUT)} with ${Object.keys(ordered).length} readings`);
